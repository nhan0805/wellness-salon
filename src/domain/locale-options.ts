export const CURRENCY_OPTIONS: CurrencyOption[] = currencyData.map(({ value, name, symbol }) => {
  const symbolSuffix = symbol !== value && String(symbol) !== '¤' ? ` (${symbol})` : '';
  return { value, name, symbol, label: `${value} — ${name}${symbolSuffix}` };
});

export function timezoneGroup(value: string) {
  return value.includes('/') ? value.split('/')[0] : 'Other';
}
